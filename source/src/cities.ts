export interface City {
  name: string
  region: string
}

export const CITIES: City[] = Object.entries(BY_REGION).flatMap(([region, names]) => names.map((name) => ({ name, region })))

/** Arabic search normalisation: hamza forms, taa marbuta, alef maqsura, tatweel, diacritics. */
export const normAr = (s: string) =>
  s
    .replace(/[ً-ْـ]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()

export function searchCities(q: string, limit = 8): City[] {
  const n = normAr(q)
  if (!n) return CITIES.filter((c) => ['الرياض', 'جدة', 'مكة المكرمة', 'المدينة المنورة', 'الدمام', 'الخبر', 'الطائف', 'أبها'].includes(c.name))
  const strip = (s: string) => s.replace(/^ال/, '')
  const starts: City[] = []
  const contains: City[] = []
  for (const c of CITIES) {
    const cn = normAr(c.name)
    if (cn.startsWith(n) || strip(cn).startsWith(strip(n))) starts.push(c)
    else if (cn.includes(n) || normAr(c.region).includes(n)) contains.push(c)
  }
  return [...starts, ...contains].slice(0, limit)
}
